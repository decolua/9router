import {pipeline, env} from '@huggingface/transformers';
import {writeFileSync, appendFileSync} from 'node:fs';

env.cacheDir = process.env.RUNNER_TEMP || '/tmp';
const started = Date.now();
const models = [
  'onnx-community/Qwen2.5-1.5B-Instruct',
  'onnx-community/Qwen2.5-0.5B-Instruct',
];
const projects = [
  ['SmartServe', 'offline restaurant ordering simulator with mock orders, KDS and manager UI'],
  ['OMEGA X', 'AI-generation app MVP, safe inputs, provider configuration and output validation'],
  ['Share App', 'secure file-sharing MVP with access control, expiration and upload limits'],
  ['MDGx1', 'AI assistant prototype with permission-gated tools and reliability checks'],
  ['Shadowbound', 'original animation preproduction with creative assets and measurable milestones'],
];
const dayIndex = Math.floor(Date.now() / 86400000);
const [name, objective] = projects[dayIndex % projects.length];
let model, engine, loadFailure;
for (const candidate of models) {
  try {
    engine = await pipeline('text-generation', candidate, {dtype: 'q4'});
    model = candidate;
    break;
  } catch (error) {
    loadFailure = String(error?.message || error).slice(0, 100);
    console.warn('MODEL_LOAD_FAILED', candidate, loadFailure);
  }
}
if (!engine) throw Error('No open-source model could be loaded');

const messages = [
  {role: 'system', content: 'You are Agent 01, a narrow, read-only project supervisor. Apply Superpowers: short plan, failing acceptance test when possible, implementation checklist, independent verification, and truthfulness. Do not claim to have changed apps, created revenue, inspected private data, deployed a system, or connected external tools. Produce 3 specific tasks and 3 acceptance tests. Avoid vague promises. Under 180 words.'},
  {role: 'user', content: 'Create today\'s concrete work plan for ' + name + ': ' + objective + '. Clarify what remains unverified. Do not assert that tasks were executed.'}
];
const result = await engine(messages, {max_new_tokens: 250, do_sample: false});
const output = result?.[0]?.generated_text;
const answer = Array.isArray(output) ? output.at(-1)?.content : typeof output === 'string' ? output : '';
if (!answer || typeof answer !== 'string' || !answer.trim()) throw Error('Empty AI output');

const report = [
  '# Agent 01 — Daily independent model run',
  '',
  'Date: ' + new Date().toISOString(),
  'Project: ' + name,
  'Model: ' + model,
  'Inference: VERIFIED (text generated by the local open-source model in GitHub Actions)',
  'External changes: NONE — planning only',
  'Scope: one project per day, five-project rotation',
  '',
  '## Today\'s suggested action',
  '',
  answer,
  '',
  'Runtime: ' + Math.round((Date.now() - started) / 1000) + ' seconds',
  ''
].join('\n');
writeFileSync('agent01-daily-report.md', report);
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, report);
console.log('AGENT01_DAILY_INFERENCE_SUCCEEDED', name);
console.log('AGENT01_DAILY_MODEL', model);
console.log('AGENT01_DAILY_SECONDS', Math.round((Date.now() - started) / 1000));
