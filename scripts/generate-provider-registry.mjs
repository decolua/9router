import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REGISTRY_DIR = path.resolve(SCRIPT_DIR, "../open-sse/providers/registry");
const INDEX_PATH = path.join(REGISTRY_DIR, "index.js");

const EXCLUSIONS = new Map([
  ["REGISTRY_TEMPLATE.js", "template file, not a provider registry entry"],
  ["devin-cli.js", "disabled because it spawns a local agent with shell/filesystem access"],
  ["index.js", "generated output"],
  ["trae.js", "disabled because Trae SOLO does not support tool calling"],
  ["windsurf.js", "disabled because its gRPC stream does not handle ToolCallChunk"],
]);

const compareNames = (left, right) => left < right ? -1 : left > right ? 1 : 0;

function importName(filename) {
  const stem = filename.slice(0, -path.extname(filename).length);
  const pascalName = stem
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  return `provider${pascalName}`;
}

async function buildIndex() {
  const filenames = (await readdir(REGISTRY_DIR))
    .filter((filename) => filename.endsWith(".js") && !EXCLUSIONS.has(filename))
    .sort(compareNames);

  const imports = filenames.map((filename) => ({
    filename,
    name: importName(filename),
  }));
  const duplicateNames = imports
    .map(({ name }) => name)
    .filter((name, index, names) => names.indexOf(name) !== index);
  if (duplicateNames.length > 0) {
    throw new Error(`Provider filenames produce duplicate import names: ${[...new Set(duplicateNames)].join(", ")}`);
  }

  const exclusionComments = [...EXCLUSIONS.entries()]
    .sort(([left], [right]) => compareNames(left, right))
    .map(([filename, reason]) => `// - ${filename}: ${reason}`)
    .join("\n");
  const importLines = imports
    .map(({ filename, name }) => `import ${name} from "./${filename}";`)
    .join("\n");
  const arrayLines = imports
    .map(({ name }) => `  ${name},`)
    .join("\n");

  return `// Generated by scripts/generate-provider-registry.mjs. Do not edit.\n// Exclusions:\n${exclusionComments}\n\n${importLines}\n\nexport default [\n${arrayLines}\n];\n`;
}

async function readCurrentIndex() {
  try {
    return await readFile(INDEX_PATH, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
}

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.length === 1 && args[0] === "--check";
  if (args.length > 0 && !checkOnly) {
    console.error("Usage: node scripts/generate-provider-registry.mjs [--check]");
    process.exitCode = 2;
    return;
  }

  const expected = await buildIndex();
  const current = await readCurrentIndex();

  if (checkOnly) {
    if (current !== expected) {
      console.error("Provider registry index is stale. Run: npm run generate:provider-registry");
      process.exitCode = 1;
      return;
    }
    console.log("Provider registry index is current.");
    return;
  }

  if (current !== expected) {
    await writeFile(INDEX_PATH, expected, "utf8");
    console.log("Generated open-sse/providers/registry/index.js");
  } else {
    console.log("Provider registry index is already current.");
  }
}

await main();
